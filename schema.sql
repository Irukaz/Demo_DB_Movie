CREATE TABLE IF NOT EXISTS cinema67.branch (
  BRANCH_ID bigint GENERATED BY DEFAULT AS IDENTITY,
  BRANCH_NAME varchar (200) NOT NULL,
  LOCATION varchar (500) NOT NULL,
  CONSTRAINT PK_BRANCH PRIMARY KEY (BRANCH_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.employee (
  EMPLOYEE_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  BRANCH_ID bigint NOT NULL,
  NAME varchar (200) NOT NULL ,
  EMAIL varchar (255),
  PHONE varchar (20),
  ROLE varchar (50) NOT NULL ,
  STATUS varchar (50) NOT NULL ,
  CONSTRAINT PK_EMPLOYEE PRIMARY KEY (EMPLOYEE_ID),
  CONSTRAINT FK_EMPLOYEE_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES cinema67.branch(BRANCH_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.theater (
  THEATER_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  BRANCH_ID bigint NOT NULL,
  THEATER_NAME varchar (100) NOT NULL,
  THEATER_TYPE varchar (50) NOT NULL ,
  THEATER_NUMBER varchar (20) NOT NULL ,
  CONSTRAINT PK_THEATER PRIMARY KEY (THEATER_ID),
  CONSTRAINT FK_THEATER_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES cinema67.branch(BRANCH_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.seat (
  SEAT_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  THEATER_ID bigint NOT NULL ,
  SEAT_NUMBER varchar (20) NOT NULL ,
  ZONE_TYPE varchar (50),
  BASE_PRICE numeric (10,2) NOT NULL ,
  CONSTRAINT PK_SEAT PRIMARY KEY (SEAT_ID),
  CONSTRAINT FK_SEAT_THEATER FOREIGN KEY (THEATER_ID) REFERENCES cinema67.theater(THEATER_ID),
  CONSTRAINT UQ_SEAT_THEATER_NUMBER UNIQUE (THEATER_ID, SEAT_NUMBER)
);

CREATE TABLE IF NOT EXISTS cinema67.movie (
  MOVIE_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  EMPLOYEE_ID bigint NOT NULL ,
  MOVIE_NAME varchar (255) NOT NULL ,
  MOVIE_DESCRIPTION varchar (1000) NOT NULL ,
  CONSTRAINT PK_MOVIE PRIMARY KEY (MOVIE_ID),
  CONSTRAINT FK_MOVIE_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES cinema67.employee(EMPLOYEE_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.showtime (
  SHOWTIME_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  THEATER_ID bigint NOT NULL ,
  MOVIE_ID bigint NOT NULL ,
  SHOW_DATE DATE NOT NULL ,
  SHOW_TIME varchar (5) NOT NULL ,
  SHOW_STATUS varchar (50) NOT NULL ,
  CONSTRAINT PK_SHOWTIME PRIMARY KEY (SHOWTIME_ID),
  CONSTRAINT FK_SHOWTIME_THEATER FOREIGN KEY (THEATER_ID) REFERENCES cinema67.theater(THEATER_ID),
  CONSTRAINT FK_SHOWTIME_MOVIE FOREIGN KEY (MOVIE_ID) REFERENCES cinema67.movie(MOVIE_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.showtime_seat (
  SHOWTIME_SEAT_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  SHOWTIME_ID bigint NOT NULL ,
  SEAT_ID bigint NOT NULL ,
  SEAT_STATUS varchar (50) NOT NULL ,
  CONSTRAINT PK_SHOWTIME_SEAT PRIMARY KEY (SHOWTIME_SEAT_ID),
  CONSTRAINT FK_SHOWTIME_SEAT_SHOWTIME FOREIGN KEY (SHOWTIME_ID) REFERENCES cinema67.showtime(SHOWTIME_ID),
  CONSTRAINT FK_SHOWTIME_SEAT_SEAT FOREIGN KEY (SEAT_ID) REFERENCES cinema67.seat(SEAT_ID),
  CONSTRAINT UQ_SHOWTIME_SEAT UNIQUE (SHOWTIME_ID, SEAT_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.promotion (
  PROMOTION_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  EMPLOYEE_ID bigint NOT NULL ,
  PROMOTION_NAME varchar (255) NOT NULL ,
  PROMOTION_CODE varchar (50) NOT NULL ,
  DISCOUNT_RATE numeric (5,2) NOT NULL ,
  IS_DELETED numeric (1) DEFAULT 0 NOT NULL ,
  CONSTRAINT PK_PROMOTION PRIMARY KEY (PROMOTION_ID),
  CONSTRAINT UQ_PROMOTION_CODE UNIQUE (PROMOTION_CODE),
  CONSTRAINT CK_PROMOTION_DELETED CHECK (IS_DELETED IN (0,1)),
  CONSTRAINT FK_PROMOTION_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES cinema67.employee(EMPLOYEE_ID)
);

