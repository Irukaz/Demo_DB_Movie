-- Merge legacy duplicates before enabling the new account constraints.
DO $$
DECLARE duplicate record;
BEGIN
  FOR duplicate IN SELECT lower(email) AS value, min(customer_id) AS keep_id FROM cinema67.customer GROUP BY lower(email) HAVING count(*) > 1 LOOP
    UPDATE cinema67.customer_order SET customer_id=duplicate.keep_id WHERE customer_id IN (SELECT customer_id FROM cinema67.customer WHERE lower(email)=duplicate.value AND customer_id<>duplicate.keep_id);
    UPDATE cinema67.complaint SET customer_id=duplicate.keep_id WHERE customer_id IN (SELECT customer_id FROM cinema67.customer WHERE lower(email)=duplicate.value AND customer_id<>duplicate.keep_id);
    DELETE FROM cinema67.customer WHERE lower(email)=duplicate.value AND customer_id<>duplicate.keep_id;
  END LOOP;
  FOR duplicate IN SELECT phone AS value, min(customer_id) AS keep_id FROM cinema67.customer GROUP BY phone HAVING count(*) > 1 LOOP
    UPDATE cinema67.customer_order SET customer_id=duplicate.keep_id WHERE customer_id IN (SELECT customer_id FROM cinema67.customer WHERE phone=duplicate.value AND customer_id<>duplicate.keep_id);
    UPDATE cinema67.complaint SET customer_id=duplicate.keep_id WHERE customer_id IN (SELECT customer_id FROM cinema67.customer WHERE phone=duplicate.value AND customer_id<>duplicate.keep_id);
    DELETE FROM cinema67.customer WHERE phone=duplicate.value AND customer_id<>duplicate.keep_id;
  END LOOP;
END $$;
