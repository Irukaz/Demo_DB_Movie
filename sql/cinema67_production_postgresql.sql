BEGIN;
-- Cinema67 production DDL: report business model, PostgreSQL.
-- 15 business tables. Additional ticket status supports cancellation/rebooking;
-- promotion kind/minimum retain the existing demonstration offers.
CREATE SCHEMA IF NOT EXISTS cinema67;
CREATE TABLE IF NOT EXISTS cinema67.customer (
  CUSTOMER_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  FIRST_NAME varchar (100) NOT NULL ,
  LAST_NAME varchar (100) NOT NULL ,
  PHONE varchar (20),
  EMAIL varchar (255),
  CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.employee (
  EMPLOYEE_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  NAME varchar (200) NOT NULL ,
  EMAIL varchar (255),
  PHONE varchar (20),
  ROLE varchar (50) NOT NULL ,
  STATUS varchar (50) NOT NULL ,
  CONSTRAINT PK_EMPLOYEE PRIMARY KEY (EMPLOYEE_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.theater (
  THEATER_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  THEATER_TYPE varchar (50) NOT NULL ,
  THEATER_NUMBER varchar (20) NOT NULL ,
  CONSTRAINT PK_THEATER PRIMARY KEY (THEATER_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.seat (
  SEAT_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  THEATER_ID bigint NOT NULL ,
  SEAT_NUMBER varchar (20) NOT NULL ,
  ZONE_TYPE varchar (50),
  BASE_PRICE numeric (10,2) NOT NULL ,
  CONSTRAINT PK_SEAT PRIMARY KEY (SEAT_ID),
  CONSTRAINT FK_SEAT_THEATER FOREIGN KEY (THEATER_ID) REFERENCES cinema67.theater(THEATER_ID),
  CONSTRAINT UQ_SEAT_THEATER_NUMBER UNIQUE (THEATER_ID, SEAT_NUMBER)
);

CREATE TABLE IF NOT EXISTS cinema67.movie (
  MOVIE_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  EMPLOYEE_ID bigint NOT NULL ,
  TITLE varchar (255) NOT NULL ,
  DURATION_MIN integer NOT NULL ,
  RELEASE_DATE DATE ,
  CONSTRAINT PK_MOVIE PRIMARY KEY (MOVIE_ID),
  CONSTRAINT FK_MOVIE_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES cinema67.employee(EMPLOYEE_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.showtime (
  SHOWTIME_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  THEATER_ID bigint NOT NULL ,
  MOVIE_ID bigint NOT NULL ,
  SHOW_DATE DATE NOT NULL ,
  SHOW_TIME varchar (5) NOT NULL ,
  SHOW_STATUS varchar (50) NOT NULL ,
  CONSTRAINT PK_SHOWTIME PRIMARY KEY (SHOWTIME_ID),
  CONSTRAINT FK_SHOWTIME_THEATER FOREIGN KEY (THEATER_ID) REFERENCES cinema67.theater(THEATER_ID),
  CONSTRAINT FK_SHOWTIME_MOVIE FOREIGN KEY (MOVIE_ID) REFERENCES cinema67.movie(MOVIE_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.showtime_seat (
  SHOWTIME_SEAT_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  SHOWTIME_ID bigint NOT NULL ,
  SEAT_ID bigint NOT NULL ,
  SEAT_STATUS varchar (50) NOT NULL ,
  CONSTRAINT PK_SHOWTIME_SEAT PRIMARY KEY (SHOWTIME_SEAT_ID),
  CONSTRAINT FK_SHOWTIME_SEAT_SHOWTIME FOREIGN KEY (SHOWTIME_ID) REFERENCES cinema67.showtime(SHOWTIME_ID),
  CONSTRAINT FK_SHOWTIME_SEAT_SEAT FOREIGN KEY (SEAT_ID) REFERENCES cinema67.seat(SEAT_ID),
  CONSTRAINT UQ_SHOWTIME_SEAT UNIQUE (SHOWTIME_ID, SEAT_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.promotion (
  PROMOTION_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  EMPLOYEE_ID bigint NOT NULL ,
  PROMOTION_NAME varchar (255) NOT NULL ,
  PROMOTION_CODE varchar (50) NOT NULL ,
  DISCOUNT_KIND varchar(10) NOT NULL DEFAULT 'percent' CHECK(DISCOUNT_KIND IN ('percent','amount')),
  MINIMUM_AMOUNT numeric(10,2) NOT NULL DEFAULT 0 CHECK(MINIMUM_AMOUNT >= 0),
  DISCOUNT_RATE numeric (5,2) NOT NULL ,
  IS_DELETED numeric (1) DEFAULT 0 NOT NULL ,
  CONSTRAINT PK_PROMOTION PRIMARY KEY (PROMOTION_ID),
  CONSTRAINT UQ_PROMOTION_CODE UNIQUE (PROMOTION_CODE),
  CONSTRAINT CK_PROMOTION_DELETED CHECK (IS_DELETED IN (0,1)),
  CONSTRAINT FK_PROMOTION_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES cinema67.employee(EMPLOYEE_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.customer_order (
  ORDER_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  CUSTOMER_ID bigint NOT NULL ,
  ORDER_DATE timestamp without time zone NOT NULL ,
  ORDER_STATUS varchar (50) NOT NULL ,
  TOTAL_AMOUNT numeric (10,2) NOT NULL ,
  CONSTRAINT PK_CUSTOMER_ORDER PRIMARY KEY (ORDER_ID),
  CONSTRAINT FK_ORDER_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES cinema67.customer(CUSTOMER_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.payment (
  PAYMENT_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  ORDER_ID bigint NOT NULL ,
  AMOUNT numeric (10,2) NOT NULL ,
  PAYMENT_STATUS varchar (50) NOT NULL ,
  PAYMENT_DATETIME TIMESTAMP NOT NULL ,
  CONSTRAINT PK_PAYMENT PRIMARY KEY (PAYMENT_ID),
  CONSTRAINT UQ_PAYMENT_ORDER UNIQUE (ORDER_ID),
  CONSTRAINT FK_PAYMENT_ORDER FOREIGN KEY (ORDER_ID) REFERENCES cinema67.customer_order(ORDER_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.ticket (
  TICKET_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  ORDER_ID bigint NOT NULL ,
  SHOWTIME_SEAT_ID bigint NOT NULL ,
  PROMOTION_ID bigint ,
  TICKET_CODE varchar (100) NOT NULL ,
  BOOK_DATETIME TIMESTAMP NOT NULL ,
  CONSTRAINT PK_TICKET PRIMARY KEY (TICKET_ID),
  CONSTRAINT UQ_TICKET_CODE UNIQUE (TICKET_CODE),
  TICKET_STATUS varchar(50) NOT NULL,
  CONSTRAINT CK_TICKET_STATUS CHECK(TICKET_STATUS IN ('HELD','BOOKED','CANCELLED','EXPIRED','CHANGED')),
  CONSTRAINT FK_TICKET_ORDER FOREIGN KEY (ORDER_ID) REFERENCES cinema67.customer_order(ORDER_ID),
  CONSTRAINT FK_TICKET_SHOWTIME_SEAT FOREIGN KEY (SHOWTIME_SEAT_ID) REFERENCES cinema67.showtime_seat(SHOWTIME_SEAT_ID),
  CONSTRAINT FK_TICKET_PROMOTION FOREIGN KEY (PROMOTION_ID) REFERENCES cinema67.promotion(PROMOTION_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.food_drink_coupon (
  COUPON_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  ORDER_ID bigint NOT NULL ,
  COUPON_CODE varchar (100) NOT NULL ,
  ITEM_TYPE varchar (100) NOT NULL ,
  STATUS varchar (50) NOT NULL ,
  REDEEM_DATETIME TIMESTAMP ,
  CONSTRAINT PK_FOOD_DRINK_COUPON PRIMARY KEY (COUPON_ID),
  CONSTRAINT UQ_COUPON_CODE UNIQUE (COUPON_CODE),
  CONSTRAINT FK_COUPON_ORDER FOREIGN KEY (ORDER_ID) REFERENCES cinema67.customer_order(ORDER_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.complaint (
  PROBLEM_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  CUSTOMER_ID bigint NOT NULL ,
  PROBLEM_DETAIL varchar (1000) NOT NULL ,
  STATUS varchar (50) NOT NULL ,
  CONSTRAINT PK_COMPLAINT PRIMARY KEY (PROBLEM_ID),
  CONSTRAINT FK_COMPLAINT_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES cinema67.customer(CUSTOMER_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.booking_operation (
  OPERATION_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  EMPLOYEE_ID bigint NOT NULL ,
  TICKET_ID bigint NOT NULL ,
  OPERATION_TYPE varchar (100) NOT NULL ,
  OPERATION_DATETIME TIMESTAMP NOT NULL ,
  CONSTRAINT PK_BOOKING_OPERATION PRIMARY KEY (OPERATION_ID),
  CONSTRAINT FK_BOOKING_OP_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES cinema67.employee(EMPLOYEE_ID),
  CONSTRAINT FK_BOOKING_OP_TICKET FOREIGN KEY (TICKET_ID) REFERENCES cinema67.ticket(TICKET_ID)
);

CREATE TABLE IF NOT EXISTS cinema67.complaint_operation (
  OPERATION_ID bigint GENERATED BY DEFAULT AS IDENTITY ,
  EMPLOYEE_ID bigint NOT NULL ,
  PROBLEM_ID bigint NOT NULL ,
  OPERATION_TYPE varchar (100) NOT NULL ,
  OPERATION_DATETIME TIMESTAMP NOT NULL ,
  CONSTRAINT PK_COMPLAINT_OPERATION PRIMARY KEY (OPERATION_ID),
  CONSTRAINT FK_COMPLAINT_OP_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES cinema67.employee(EMPLOYEE_ID),
  CONSTRAINT FK_COMPLAINT_OP_PROBLEM FOREIGN KEY (PROBLEM_ID) REFERENCES cinema67.complaint(PROBLEM_ID)
);


CREATE UNIQUE INDEX IF NOT EXISTS uq_ticket_active_showtime_seat ON cinema67.ticket(showtime_seat_id) WHERE ticket_status IN ('HELD','BOOKED');

COMMIT;
