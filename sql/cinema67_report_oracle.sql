CREATE TABLE CUSTOMER (
  CUSTOMER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
  FIRST_NAME VARCHAR2 (100) NOT NULL ,
  LAST_NAME VARCHAR2 (100) NOT NULL ,
  PHONE VARCHAR2 (20),
  EMAIL VARCHAR2 (255),
  CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE EMPLOYEE (
  EMPLOYEE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
  NAME VARCHAR2 (200) NOT NULL ,
  EMAIL VARCHAR2 (255),
  PHONE VARCHAR2 (20),
  ROLE VARCHAR2 (50) NOT NULL ,
  STATUS VARCHAR2 (50) NOT NULL ,
  CONSTRAINT PK_EMPLOYEE PRIMARY KEY (EMPLOYEE_ID)
);

CREATE TABLE THEATER (
  THEATER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
  THEATER_TYPE VARCHAR2 (50) NOT NULL ,
  THEATER_NUMBER VARCHAR2 (20) NOT NULL ,
  CONSTRAINT PK_THEATER PRIMARY KEY (THEATER_ID)
);

CREATE TABLE SEAT (
  SEAT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
  THEATER_ID NUMBER NOT NULL ,
  SEAT_NUMBER VARCHAR2 (20) NOT NULL ,
  ZONE_TYPE VARCHAR2 (50),
  BASE_PRICE NUMBER (10,2) NOT NULL ,
  CONSTRAINT PK_SEAT PRIMARY KEY (SEAT_ID),
  CONSTRAINT FK_SEAT_THEATER FOREIGN KEY (THEATER_ID) REFERENCES THEATER(THEATER_ID),
  CONSTRAINT UQ_SEAT_THEATER_NUMBER UNIQUE (THEATER_ID, SEAT_NUMBER)
);

CREATE TABLE MOVIE (
  MOVIE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
  EMPLOYEE_ID NUMBER NOT NULL ,
  TITLE VARCHAR2 (255) NOT NULL ,
  DURATION_MIN NUMBER NOT NULL ,
  RELEASE_DATE DATE ,
  CONSTRAINT PK_MOVIE PRIMARY KEY (MOVIE_ID),
  CONSTRAINT FK_MOVIE_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE TABLE SHOWTIME (
  SHOWTIME_ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
  THEATER_ID NUMBER NOT NULL ,
  MOVIE_ID NUMBER NOT NULL ,
  SHOW_DATE DATE NOT NULL ,
  SHOW_TIME VARCHAR2 (5) NOT NULL ,
  SHOW_STATUS VARCHAR2 (50) NOT NULL ,
  CONSTRAINT PK_SHOWTIME PRIMARY KEY (SHOWTIME_ID),
  CONSTRAINT FK_SHOWTIME_THEATER FOREIGN KEY (THEATER_ID) REFERENCES THEATER(THEATER_ID),
  CONSTRAINT FK_SHOWTIME_MOVIE FOREIGN KEY (MOVIE_ID) REFERENCES MOVIE(MOVIE_ID)
);

CREATE TABLE SHOWTIME_SEAT (
  SHOWTIME_SEAT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
  SHOWTIME_ID NUMBER NOT NULL ,
  SEAT_ID NUMBER NOT NULL ,
  SEAT_STATUS VARCHAR2 (50) NOT NULL ,
  CONSTRAINT PK_SHOWTIME_SEAT PRIMARY KEY (SHOWTIME_SEAT_ID),
  CONSTRAINT FK_SHOWTIME_SEAT_SHOWTIME FOREIGN KEY (SHOWTIME_ID) REFERENCES SHOWTIME(SHOWTIME_ID),
  CONSTRAINT FK_SHOWTIME_SEAT_SEAT FOREIGN KEY (SEAT_ID) REFERENCES SEAT(SEAT_ID),
  CONSTRAINT UQ_SHOWTIME_SEAT UNIQUE (SHOWTIME_ID, SEAT_ID)
);

CREATE TABLE PROMOTION (
  PROMOTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
  EMPLOYEE_ID NUMBER NOT NULL ,
  PROMOTION_NAME VARCHAR2 (255) NOT NULL ,
  PROMOTION_CODE VARCHAR2 (50) NOT NULL ,
  DISCOUNT_RATE NUMBER (5,2) NOT NULL ,
  IS_DELETED NUMBER (1) DEFAULT 0 NOT NULL ,
  CONSTRAINT PK_PROMOTION PRIMARY KEY (PROMOTION_ID),
  CONSTRAINT UQ_PROMOTION_CODE UNIQUE (PROMOTION_CODE),
  CONSTRAINT CK_PROMOTION_DELETED CHECK (IS_DELETED IN (0,1)),
  CONSTRAINT FK_PROMOTION_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE TABLE CUSTOMER_ORDER (
